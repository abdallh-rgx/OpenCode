④ 회사는 다음 각 호의 행위의 구체적인 내용을 정할 수 있으며, 회원은 이를 따라야 합니다.
  1. 회원의 계정명, 캐릭터명, 길드명, 기타 게임 내에서 사용하는 명칭
  2. 채팅내용과 방법
  3. 게시판이용 및 서비스이용 방법
