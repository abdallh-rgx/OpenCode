4.4 Việc đặt tên tài khoản, tên nhân vật của Bạn trong Trò Chơi cần phải tuân thủ nguyên tắc đặt tên đã được công bố.
4.5Bạn hiểu rõ và đồng ý rằng, VNG và/hoặc bên thứ ba hợp tác với VNG có thể căn cứ theo các thông tin do Bạn cung cấp để gửi đến Bạn các thông tin quảng cáo, thông tin hoạt động của Trò Chơi thông qua các hình thức như tin nhắn, điện thoại, thư điện tử (email) … hoặc bất kỳ hình thức nào khác mà Bạn có thể tiếp nhận được thông tin; trong trường hợp này, bên thứ ba hợp tác với VNG (nếu có)  cũng có nghĩa vụ bảo mật Thông Tin Cá Nhân của Bạn như VNG.
4.6Bạn hiểu rõ và đồng ý rằng, để tránh trường hợp bị mất, bị can thiệp vào tài khoản ngoài ý muốn (như bị hack) , Bạn sẽ không tiết lộ (bất kể là vô tình hay hữu ý)  thông tin về tài khoản, mật khẩu của Bạn trong Trò Chơi cho bất kỳ bên thứ ba nào, kể cả những người thân thích của Bạn; đồng thời, áp dụng các biện pháp hợp lý nhằm bảo mật tài khoản của Bạn. Trong bất kỳ trường hợp nào, Bạn nhận thấy hay nghi ngờ tài khoản của mình bị đăng nhập trái với ý muốn của Bạn, Bạn có thể (i) ngay lập tức thay đổi mật khẩu và/hoặc (ii)  thông báo cho VNG và thực hiện các thủ tục cần thiết tạm khóa tài khoản nhằm giảm thiểu các thiệt hại cho Bạn theo đúng quy trình hỗ trợ giải quyết khiếu nại khách hàng của VNG.
4.7Bạn hiểu rõ và đồng ý rằng, để tăng cường mức độ bảo mật, an toàn của dịch vụ, VNG có quyền áp dụng một hoặc một vài biện pháp kỹ thuật và/hoặc phần mềm, ứng dụng vào trong hoặc bên cạnh Trò Chơi; mặc dù vậy, việc áp dụng các biện pháp nêu trên không được là sự đảm bảo rằng tài khoản của Bạn không bị mất, bị hack và VNG được miễn trừ hoàn toàn trách nhiệm bởi các trường hợp này.
4.8Bạn hiểu rõ và đồng ý rằng, để nâng cao hiệu quả sử dụng tài nguyên hệ thống, trường hợp Bạn không đăng nhập, sử dụng tài khoản Trò Chơi trong vòng sáu (6)  tháng kể từ lần đăng nhập cuối cùng, VNG có quyền (nhưng không có nghĩa vụ) xóa toàn bộ tài khoản của Bạn trong Trò Chơi cùng với toàn bộ Dữ Liệu của Bạn.
4.9Để VNG có thể phục vụ Bạn tốt nhất, Bạn theo đây đồng ý, cho phép không hủy ngang rằng VNG có quyền thông qua Trò Chơi để thu thập thông tin về thiết bị và/hoặc các ứng dụng trên thiết bị của Bạn, kể cả việc gửi đến thiết bị của Bạn các phần mềm, ứng dụng nhằm thu thập một số thông tin kỹ thuật được chứa đựng trong thiết bị của Bạn. VNG sẽ bảo mật toàn bộ các thông tin này theo đúng Chính sách bảo mật của VNG.
5.Dịch Vụ Trò Chơi
5.1 Khi Bạn đã đồng ý và tuân thủ các quy định pháp luật liên quan và Quy Định Trò Chơi, VNG cấp cho Bạn quyền không độc quyền để sử dụng các dịch vụ và tính năng của Trò Chơi cho mục đích cá nhân, không thể chuyển giao, chuyển nhượng và không được thương mại hóa. Để tránh hiểu nhầm, việc VNG cấp cho Bạn quyền sử dụng các dịch vụ và tính năng của Trò Chơi sẽ không bao gồm quyền sử dụng trò chơi để thực hiện livestreaming (bất kể là có hay không có quảng cáo), tổ chức các giải đấu, thi đấu (bất kể là có nhằm mục đích thương mại hay không).
5.2 Ngoài việc sử dụng Trò Chơi được cấp cho Bạn như Điều 5.1 , VNG bảo lưu toàn bộ quyền sở hữu trí tuệ đối với nhãn hiệu, mã nguồn Sản Phẩm, hình ảnh, tính năng, âm nhạc … trong Trò Chơi, quyền thực hiện livestreaming, tổ chức giải đấu, sử dụng các hình ảnh của/có liên quan đến Trò Chơi cùng với các quyền khác liên quan đến Trò Chơi và Bạn sẽ không thực hiện bất kỳ hành động nào khác ngoài các quyền đã nêu tại khoản 5.1  Điều 5 nếu không được VNG đồng ý trước bằng văn bản. 
5.3 Bạn hiểu rõ và đồng ý rằng:
