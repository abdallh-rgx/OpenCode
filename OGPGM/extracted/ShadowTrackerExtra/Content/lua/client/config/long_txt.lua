(d) Khóa tài khoản có thời hạn (thời hạn cụ thể sẽ tùy thuộc vào hành vi, mức độ vi phạm) : Áp dụng đối với các hành vi đã bị Cảnh cáo VÀ/HOẶC đã bị xử lý theo quy định tại điểm (c)  khoản 6.2  Điều này mà không khắc phục và/hoặc tái phạm HOẶC vi phạm quy định tại các tiểu mục (vii)  điểm (b) , mục (xii) , (xiii) , (xv)  điểm (c)  khoản 6.1  Điều 6 của Điều Khoản Sử Dụng này.
