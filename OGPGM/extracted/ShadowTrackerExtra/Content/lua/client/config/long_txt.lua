제10조 (서비스의 제공) 
① 회사는 본 약관 제4조의 규정에 따라 이용계약이 완료된 회원에게 그 즉시 서비스를 이용할 수 있도록 합니다. 다만, 일부 서비스의 경우 회사의 필요에 따라 지정된 일자부터 서비스를 개시할 수 있습니다.
② 회사는 회원에게 게임서비스를 제공할 때 이 약관에 정하고 있는 서비스를 포함하여 기타 부가적인 서비스를 함께 제공할 수 있습니다.
③ 회사는 회원의 등급을 구분하고 이용시간, 이용횟수, 제공 서비스의 범위 등을 세분화하여 이용에 차등을 둘 수 있습니다.

제11조 (서비스의 이용) 
① 서비스는 회사의 영업방침에 따라 정해진 시간 동안 제공합니다. (별도의 안내가 없는 경우 연중무휴 1일 24시간 제공하는 것을 원칙으로 합니다) 단, 관련법령에서 정하는 바에 따라 서비스 제공시간 등에 제한을 두어야 하는 경우, 회사는 별도의 사전 공지 없이 서비스의 제공시간을 제한 또는 변경 할 수 있으며 이에 대하여 어떠한 책임도 부담하지 않습니다.
② 제1항에도 불구하고 회사는 다음 각 호의 경우에는 서비스의 전부 또는 일부를 일시 정지할 수 있습니다. 이 경우 회사는 사전에 그 정지의 사유와 기간을 게임 애플리케이션 초기화면이나 게임서비스 공지사항 등에 공지합니다. 다만, 사전에 공지할 수 없는 부득이한 사정이 있는 경우 사후에 공지할 수 있습니다.
1. 컴퓨터 등 정보통신설비의 보수점검, 교체, 정기점검 또는 서비스의 내용 수정을 위하여 필요한 경우
  2. 해킹 등의 전자적 침해사고, 통신사고, “회원”들의 비정상적인 게임 이용행태, 미처 예상하지 못한 서비스의 불안정성에 대응하기 위하여 필요한 경우
  3. 관련 법령에서 특정 시간 또는 방법으로 서비스 제공을 금지하는 경우
  4. 천재지변, 비상사태, 정전, 서비스 설비의 장애 또는 서비스 이용의 폭주 등으로 정상적인 서비스 제공이 불가능할 경우
5. 회사의 분할, 합병, 영업양도, 영업의 폐지, 당해 서비스의 수익 악화 등 회사의 경영상 중대한 필요에 의한 경우
③ 회사는 모바일 기기를 위한 전용 애플리케이션 또는 네트워크를 이용하여 서비스를 제공합니다. 회원은 애플리케이션을 다운로드하여 설치하거나 네트워크를 이용하여 무료 또는 유료로 서비스를 이용할 수 있습니다.
④ 유료 콘텐츠의 경우에는 해당 서비스에 명시된 요금을 지급하여야 이용할 수 있습니다. 네트워크를 통해 애플리케이션을 다운로드 하거나 서비스를 이용하는 경우에는 가입한 이동통신사에서 정한 별도의 요금이 발생할 수 있습니다.
⑤ 다운로드 하여 설치한 애플리케이션 또는 네트워크를 통해 이용하는 서비스의 경우에는 모바일 기기 또는 이동통신사의 특성에 맞도록 제공됩니다. 모바일 기기의 변경. 번호 변경 또는 해외 로밍의 경우에는 콘텐츠의 전부 또는 일부의 이용이 불가능할 수 있으며, 이 경우 회사는 책임을 지지 않습니다.
⑥ 다운로드하여 설치한 애플리케이션 또는 네트워크를 통해 이용하는 서비스의 경우에는 백그라운드 작업이 진행될 수 있습니다. 이 경우 모바일 기기 또는 이동통신사의 특성에 맞도록 추가요금이 발생할 수 있으며 이와 관련하여 회사는 책임을 지지 않습니다.

제12조 (서비스의 변경 및 중단) 
① 회사는 본 약관 제11조 제2항 제1호의 경우 주 단위 또는 월 단위로 일정 시간을 정하여 서비스를 중지할 수 있습니다. 이 경우 회사는 공식 커뮤니티 공지사항 등을 통하여 고지합니다.
② 회사는 원활한 게임서비스 제공을 위해 운영상 또는 기술상의 필요에 따라 서비스를 변경할 수 있으며, 변경 전에 해당 내용을 공식커뮤니티 내에 공지합니다. 다만, 버그 및 오류 등의 수정이나 긴급 업데이트 등 부득이하게 변경할 필요가 있는 경우 또는 중대한 변경에 해당하지 않는 경우에는 사후에 공지할 수 있습니다.
③ 회사는 무료로 제공되는 서비스의 일부 또는 전부를 회사의 정책 및 운영 필요성에 의하여 수정, 중단, 변경할 수 있습니다. 이에 대하여 관계 법령에 특별한 규정이 없는 한 회사는 회원에게 기대수익의 상실, 회사가 직접 제공하지 않은 수익의 상실 또는 기타 무료로 제공된 서비스의 수정, 중단, 변경 등으로 발생하는 손해에 대하여 별도의 보상을 하지 않습니다.
④ 회사가 기술 상 경영 상의 사유로 서비스를 영구적으로 종료하는 경우, 해당 서비스의 종료에 관한 사실을 30일 전부터 홈페이지 또는 서비스 내에 공지한 후 종료합니다. 사전에 통지할 수 없는 부득이한 사정이 있는 경우에는 사후에 통지를 할 수 있습니다.
⑤ 제4항에 따라 서비스가 종료되는 경우 회사는 사용하지 않았거나 사용기간이 남아 있는 유료 콘텐츠에 대해 제16조에 따라 환급합니다.

제13조 (정보의 수집 등) 
① 회사는 회원간에 이루어지는 채팅 내용을 저장 및 보관할 수 있으며 이 정보는 회사만이 보유합니다. 회사는 회원간의 분쟁 조정, 민원 처리 또는 게임 질서의 유지를 위한 경우에 한하여, 제3자는 법령에 따라 권한이 부여된 경우에 한하여 이 정보를 열람할 수 있습니다.
② 회사 또는 제3자가 제1항에 따라 채팅 정보를 열람할 경우 회사는 사전에 열람의 사유 및 범위를 해당 회원에게 고지합니다. 다만, 제9조 제1항에 따른 금지행위의 조사, 처리, 확인 또는 그 행위로 인한 피해 구제와 관련하여 이 정보를 열람해야 할 경우에는 사후에 고지할 수 있습니다.
③ 회사는 서비스의 원활하고 안정적인 운영 및 서비스 품질의 개선을 위하여 회원의 개인정보를 제외한 회원의 모바일 기기 정보(설정,사양,운영체제, 버전 등)를 수집 및 활용할 수 있습니다.
④ 회사는 서비스 개선 및 회원 대상 서비스 소개 등을 위한 목적으로 회원에게 추가정보를 요청할 수 있습니다. 이 요청에 대해 회원은 승낙하거나 거절할 수 있으며, 회사가 이 요청을 할 경우에는 회원이 이 요청을 거절할 수 있다는 뜻을 함께 고지합니다.

제14조 (광고의 제공) 
① 회사는 서비스의 운영과 관련하여 게임서비스 내에 광고를 게재할 수 있습니다. 또한 수신에 동의한 회원에 한하여 문자서비스(LMS/SMS), 푸시메시지(Push Notification) 등의 방법으로 광고성 정보를 전송할 수 있습니다. 이 경우 회원은 언제든지 수신을 거절할 수 있으며, 회사는 회원의 수신 거절 시 광고성 정보를 발송하지 아니합니다.  
② 회사가 제공하는 서비스 중의 배너 또는 링크 등을 통해 타인이 제공하는 광고나 서비스에 연결될 수 있습니다.
③ 제2항에 따라 타인이 제공하는 광고나 서비스에 연결될 경우 해당 영역에서 제공하는 서비스는 회사의 서비스 영역이 아니므로 회사가 신뢰성, 안정성 등을 보장하지 않으며, 그로 인한 회원의 손해에 대하여도 회사는 책임을 지지 않습니다. 다만, 회사가 고의 또는 중과실로 손해의 발생을 용이하게 하거나 손해 방지를 위한 조치를 취하지 아니한 경우에는 그러하지 아니합니다.
제15조 (저작권 등의 귀속) 
① 회사가 제작한 게임서비스 내의 콘텐츠에 대한 저작권과 기타 지적재산권은 회사에 귀속합니다.
② 회원은 회사가 제공하는 게임서비스를 이용하여 얻은 정보 중에서 회사 또는 제공업체에 지적재산권이 귀속된 정보를 회사 또는 제공업체의 사전 동의 없이 복제 및 전송 등의 방법(편집, 공표, 공연, 배포, 방송, 2차적 저작물 작성 등을 포함합니다. 이하 같습니다)에 의하여 영리목적으로 이용하거나 타인에게 이용하게 하여서는 안 됩니다.
③ 회원은 게임 내에서 보여지거나 게임서비스와 관련하여 회원 또는 다른 이용자가 게임 애플리케이션 또는 게임서비스를 통해 업로드 또는 전송하는 대화 텍스트를 포함한 커뮤니케이션, 이미지, 사운드 및 모든 자료 및 정보(이하 “이용자 콘텐츠”라 합니다.)에 대하여 회사가 다음과 같은 방법과 조건으로 이용하는 것을 허락합니다.
1. 해당 이용자 콘텐츠를 이용, 편집 형식의 변경 및 기타 변형하는 것(공표, 복제, 공연, 전송, 배포, 방송, 2차적 저작물 작성 등 어떠한 형태로든 이용 가능하며, 이용기간과 지역에는 제한이 없음)
2. 이용자 콘텐츠를 제작한 이용자의 사전 동의 없이 거래를 목적으로 이용자 콘텐츠를 판매, 대여, 양도 행위를 하지 않음
④ 게임 내에서 보여지지 않고 게임서비스와 일체화되지 않은 회원의 이용자 콘텐츠(예컨대, 일반게시판 등에서의 게시물)에 대하여 회사는 회원의 명시적인 동의가 없이 이용하지 않으며, 회원은 언제든지 이러한 이용자 콘텐츠를 삭제할 수 있습니다.
⑤ 회사는 회원이 게시하거나 등록하는 서비스 내의 게시물에 대해 제9조 제1항에 따른 금지행위에 해당된다고 판단되는 경우에는 사전 통지 없이 이를 삭제 또는 이동하거나 그 등록을 거절할 수 있습니다. 
⑥ 회사가 운영하는 게시판 등에 게시된 정보로 인하여 법률상 이익이 침해된 회원은 회사에 해당 정보의 삭제 또는 반박 내용의 게재를 요청할 수 있습니다. 이 경우 회사는 신속하게 필요한 조치를 취하고 이를 신청인에게 통지합니다.
⑦ 제16조는 회사가 게임서비스를 운영하는 동안 유효하며, 회원 탈퇴 후에도 지속적으로 적용됩니다.

제16조 (유료 콘텐츠의 구매, 사용기간 및 이용) 
① 게임서비스 내에서 회원이 구매한 유료 콘텐츠는 해당 애플리케이션을 다운로드 받거나 설치한 모바일 기기에서만 이용할 수 있습니다.
② 회원이 구매한 유료 콘텐츠의 이용기간은 구매 시 명시된 기간에 따릅니다. 다만, 제12조 제4항에 따라 서비스 중단이 이루어지는 경우 기간의 정함이 없는 유료 콘텐츠의 이용기간은 서비스 중단 공지 시 공지된 서비스의 중단일자까지로 합니다.

제17조 (회원에 대한 서비스 이용제한)
① 회원은 제9조에 따른 회원의 의무를 위반하는 행위를 하여서는 안 되며, 해당 행위를 하는 경우에 회사는 다음 각 호의 구분에 따른 회원의 서비스 이용제한, 관련 정보(글, 사진, 영상 등) 삭제 및 기타의 조치를 포함한 이용제한 조치를 할 수 있습니다. 이용제한 조치가 이루어지는 구체적인 사유 및 절차는 제6조 제1항에 따라 운영정책에서 정합니다.
  1. 캐릭터 일부 권한 제한 : 일정기간 동안 채팅 등 캐릭터의 권한을 제한
  2. 캐릭터 이용 제한 : 일정기간 또는 영구히 회원 캐릭터의 이용을 제한
  3. 단말 이용 제한 : 일정기간 또는 영구히 해당 단말의 “서비스” 접속을 제한
  4. 계정 이용 제한 : 일정기간 또는 영구히 계정의 이용을 제한
  5. 회원 이용 제한 : 일정기간 또는 영구히 “회원”의 “서비스” 이용을 제한
② 제1항의 이용제한이 정당한 경우에 회사는 이용제한으로 인하여 회원이 입은 손해를 배상하지 않습니다.
③ 회사는 다음 각 호의 사유에 대한 조사가 완료될 때까지 해당 계정의 서비스 이용을 정지할 수 있습니다.
 1. 계정이 해킹 또는 도용 당했다는 정당한 신고가 접수된 경우
 2. 불법프로그램 사용자 또는 작업장 등 위법행위자로 의심되는 경우
 3. 그 밖에 각 호에 준하는 사유로 서비스 이용 정지의 잠정조치가 필요한 경우
④ 회사가 용인하지 않는 방법을 통해 재화 및 아이템 등의 게임 정보를 획득한 경우 회사는 운영정책에 따라 서비스 이용제한,재화 및 아이템 회수 등의 필요 조치를 취할 수 있습니다.

제18조 (이용제한의 사유와 절차)
①	 회사는 제17조 제1항에 따른 이용제한 조치의 구체적인 사유 및 절차를 제9조 제1항에 따른 금지행위의 내용,정도,횟수,결과 등을 고려하여 운영정책으로 정합니다.
② 회사가 제17조에서 정한 이용제한을 하는 경우에는 회원에게 서비스 초기 화면에서 게시하는 방법으로 다음 각 호의 사항을 “회원”에게 통보합니다.
  1. 이용제한 사유
  2. 이용제한 유형 및 기간

제19조 (이용제한 조치에 대한 이의신청 절차) 
① 회원이 회사의 이용제한 조치에 불복하고자 할 때에는 이 조치의 통지를 받은 날부터 14일 이내에 불복 이유를 기재한 이의 신청서를 서면, 전자우편 또는 이에 준하는 방법으로 회사에 제출하여야 합니다.
② 회사는 제1항의 이의신청서를 접수한 날부터 15일 이내에 불복 이유에 대하여 서면, 전자우편 또는 이에 준하는 방법으로 답변합니다. 다만, 회사는 이 기간 내에 답변이 어려운 경우에는 그 사유와 처리일정을 통지합니다.
③ 회사는 불복 이유가 타당한 경우에는 이에 따른 조치를 취합니다.

제20조 (대금결제) 
① 콘텐츠에 대한 구매 대금의 부과와 납부는 원칙적으로 이동통신사나 오픈마켓 사업자 등에서 정하는 정책이나 방법에 따릅니다. 또한 각 결제수단별 한도가 회사나 오픈마켓 사업자가 정하는 정책 또는 정부의 방침에 따라 부여되거나 조정될 수 있습니다.
②	 콘텐츠의 구매대금을 외화로 결제하는 경우에는 환율 또는 수수료 등으로 인하여 실제 청구금액이 서비스의 상점 등에서 표시된 가격과 달라질 수 있습니다.

제21조 (청약의 철회 등)
① 회사가 제공하는 유료 콘텐츠는 「전자상거래 등에서의 소비자보호에 관한 법률」,「콘텐츠산업진흥법」 등 관련 법령에 따라 청약철회가 가능한 것과 제한되는 것으로 구분됩니다. 청약철회가 가능한 유료 콘텐츠의 경우 회원은 해당 유료 콘텐츠의 구매 후 7일 이내에 사용하지 아니한 유료 콘텐츠에 한하여 회사에 청약철회를 요청할 수 있습니다.
② 회원은 전 항의 규정에 따라 다음 각호의 어느 하나에 해당하는 경우에는 회사의 의사에 반하여 제1항에 따른 청약철회 등을 할 수 없습니다.
  1. 회원에게 책임 있는 사유로 재화 등이 멸실되거나 훼손된 경우
  2. 회원이 재화를 사용 또는 일부 소비한 경우
  3. 구매 즉시 사용되거나 적용되는 유료 콘텐츠
4. 추가혜택이 제공되는 경우에 그 추가 혜택이 사용된 콘텐츠
5. 개봉행위를 사용으로 볼 수 있거나 개봉 시 효용이 결정되는 콘텐츠의 개봉행위가 있는 경우
  6. 그 밖에 거래의 안전을 위하여 법령으로 정하는 경우 
③ 회사는 제2항 각 호의 규정에 따라 청약철회가 불가능한 콘텐츠의 경우에는 그 사실을 회원이 쉽게 알 수 있는 곳에 명확하게 표시하고, 해당 콘텐츠의 시험사용 상품을 제공(한시적 이용의 허용, 체험용 제공 등)하거나 이에 대한 제공이 곤란한 경우에는 콘텐츠에 관한 정보를 제공함으로써 회원의 청약철회의 권리행사가 방해받지 아니하도록 조치합니다. 만약 회사가 이러한 조치를 하지 아니한 경우에는 제2항 각 호의 청약철회 제한사유에도 불구하고 회원은 청약철회를 할 수 있습니다.
④ 회원은 제1항 내지 제3항의 규정에도 불구하고 회사가 제공하는 유료 콘텐츠의 내용이 표시 또는 광고된 내용과 다르거나 계약 내용과 다르게 이행된 경우, 회원은 해당 유료 콘텐츠의 구매일로부터 3개월 이내, 그 사실을 안 날 또는 알 수 있었던 날로부터 30일 이내에 청약철회가 가능합니다.
⑤ 회원이 청약철회를 할 경우 회사는 플랫폼사업자 또는 오픈마켓 사업자를 통해 구매내역을 확인합니다. 또한 회사는 회원의 정당한 철회 사유를 확인하기 위해 회원에게서 제공받은 정보를 통해 회원에게 연락할 수 있으며, 추가적인 증빙을 요구할 수 있습니다.
⑥ 미성년자가 모바일 기기에서 콘텐츠 구매계약을 체결하는 경우, 회사는 법정대리인의 동의가 없으면 미성년자 본인 또는 법정대리인이 그 계약을 취소할 수 있다는 내용을 고지하며, 미성년자가 법정대리인의 동의 없이 구매계약을 체결한 때에는 미성년자 본인 또는 법정대리인은 회사에 그 계약을 취소할 수 있습니다. 다만, 미성년자가 법정대리인이 범위를 정하여 처분을 허락한 재산으로 콘텐츠를 구매한 경우 또는 미성년자가 속임수로써 자기를 성년자로 믿게 하거나 법정대리인의 동의가 있는 것으로 믿게 한 경우에는 취소할 수 없습니다. 
⑦ 유료 콘텐츠 구매자가 미성년자인지 여부는 결제가 진행된 단말기, 결제 실행자 정보, 결제 수단 명의자 등의 근거 기록을 토대로 판단됩니다. 이를 위하여 회사는 필요에 따라 미성년자 및 법정대리인을 증명할 수 있는 서류 제출을 요구할 수 있습니다.
⑧ 회사가 회원에게 무료로 지급 경우에는 청약철회의 대상에서 제외됩니다.

제22조 (청약철회 등의 효과)
① 회원이 청약철회를 한 경우 회사는 지체 없이 회원의 유료 콘텐츠를 회수 또는 삭제하고, 환급에 필요한 서류 등을 접수한 날로부터 3영업일 이내에 오픈마켓사업자에 대한 결제취소요청 등 환급에 필요한 절차를 개시합니다. 이 경우 회사의 귀책사유로 환급이 지연될 경우 그 지연기간에 대하여 「전자상거래 등에서의 소비자보호에 관한 법률」 및 같은 법 시행령 제21조의3에서 정하는 이율을 곱하여 산정한 지연이자를 지급합니다.
② 회사는 결제대금을 환급함에 있어 회원이 신용카드나 그 밖에 “전자상거래 등에서의 소비자보호에 관한 법률 시행령”으로 정하는 결제수단으로 대금을 지급한 때에는 지체 없이 당해 결제수단을 제공한 사업자로 하여금 결제대금의 청구를 정지 또는 취소하도록 요청합니다. 다만 회사가 결제업자로부터 이미 대금을 지급받은 때에는 이를 결제업자에게 환급하고 이를 소비자에게 통지합니다.
③ 회사는 아이템 등이 일부 사용되거나 소비된 경우에는 회원이 얻은 이익 또는 해당 아이템 등의 공급에 든 비용에 상당하는 금액을 회원에게 청구할 수 있습니다.
④ 회사는 필요한 경우 회원에게 환급에 필요한 서류를 요구할 수 있으며, 회원이 이를 거부할 경우에는 환급이 제한될 수 있습니다.

제23조 (과오납금의 환급)
① 회사는 과오납금이 발생하는 경우 과오납금을 회원에게 환급합니다. 다만, 과오납금이 회사의 고의 또는 과실 없이 회원의 과실로 인하여 발생한 경우에는 그 환급에 소요되는 실제 비용은 합리적인 범위 내에서 회원이 부담합니다.
② 애플리케이션을 통한 결제는 오픈마켓 사업자가 제공하는 결제방식에 따르며, 결제 과정에서 과오납금이 발생하는 경우, 회사 또는 오픈마켓 사업자에게 환급을 요청하여야 합니다.
③ 애플리케이션의 다운로드 또는 네트워크 서비스의 이용으로 인해 발생한 통신요금(통화료, 데이터 통화료 등)은 환급 대상에서 제외될 수 있습니다.
④ 환급은 서비스를 이용하고 있는 모바일 기기의 운영체제 종류에 따라 각 오픈마켓 사업자 또는 회사의 환급정책에 따라 진행됩니다.
⑤ 회사는 과오납금의 환급을 처리하기 위해 회원에게서 제공받은 정보를 통해 회원에게 연락할 수 있으며, 필요한 정보의 제공을 요청할 수 있습니다. 회사는 회원으로부터 환급에 필요한 정보를 받은 날부터 3영업일 이내에 환급합니다.
⑥ “회사”는 “회원”이 주장하는 과오금에 대해 환불을 거부할 경우에 정당하게 이용대금이 부과되었음을 입증할 책임을 집니다.

제24조 (회원의 해제 및 해지)
① 회원은 언제든지 서비스 이용을 원하지 않는 경우 고객센터 내 회원탈퇴 절차를 통하여 회원탈퇴를 할 수 있습니다. 회원탈퇴로 인해 회원이 게임서비스 내에서 보유한 게임이용정보(점수, 캐릭터, 아이템, 게임머니 등)는 모두 삭제되어 복구가 불가능하게 됩니다.
② 회사는 회원이 이 약관 및 그에 따른 운영정책, 서비스 정책에서 금지하는 행위를 하는 등 본 계약을 유지할 수 없는 중대한 사유가 있는 경우에는 상당한 기간 전에 최고하고 기간을 정하여 서비스 이용을 중지하거나 이용계약을 해지할 수 있습니다.
③ 회원이 회원탈퇴를 신청한 경우 회사는 회원 본인 여부를 확인할 수 있으며, 해당 회원이 본인으로 확인되는 경우 회원의 신청에 따른 조치를 취합니다.
④ 회사는 최근의 서비스 이용일부터 연속하여 1년 동안 회사의 서비스를 이용하지 않은 휴면계정의 개인정보를 보호하기 위해 이용계약을 해지하고 회원의 개인정보 파기 등의 조치를 취할 수 있습니다. 이 경우 조치일 30일 전까지 계약해지, 개인정보 파기 등의 조치가 취해진다는 사실 및 파기될 개인정보 등을 회원에게 통지합니다.

제25조 (손해배상)
① 회사 또는 회원은 본 약관을 위반하여 상대방에게 손해를 입힌 경우에는 그 손해를 배상할 책임이 있습니다. 다만, 고의 또는 과실이 없는 경우에는 그러하지 아니 합니다
② 회사가 개별서비스 제공자와 제휴 계약을 맺고 회원에게 개별서비스를 제공하는 경우에 회원이 이 개별서비스 이용약관에 동의를 한 뒤 개별서비스 제공자의 고의 또는 과실로 인해 회원에게 손해가 발생한 경우에 그 손해에 대해서는 개별서비스 제공자가 책임을 집니다.

제26조 (회사의 면책)
① 회사는 천재지변 또는 이에 준하는 불가항력으로 인하여 서비스를 제공할 수 없는 경우에는 서비스 제공에 관하여 책임을 지지 않습니다.
② 회사는 서비스용 설비의 보수, 교체, 정기점검, 공사 등 기타 이에 준하는 사유로 발생한 손해에 대하여 책임을 지지 않습니다. 다만, 회사의 고의 또는 과실에 의한 경우에는 그러하지 아니합니다.
③ 회사는 회원의 고의 또는 과실로 인한 서비스 이용의 장애에 대하여는 책임을 지지 않습니다. 다만, 회원에게 부득이하거나 정당한 사유가 있는 경우에는 그러하지 아니합니다.
④ 회원이 서비스와 관련하여 게재한 정보나 자료 등의 신뢰성, 정확성 등에 대하여 회사는 고의 또는 중대한 과실이 없는 한 책임을 지지 않습니다.
