(b) Để đảm bảo tốc độ, sự trải nghiệm của Bạn trong Trò Chơi, VNG có quyền định kỳ hoặc tại bất kỳ thời điểm nào hợp lý thực hiện xóa Dữ Liệucũ lưu trữ trên máy chủ Trò Chơi.
